#!/usr/bin/env python3
"""DEF-SAB-AUDIT: emit src/sab_audit_registry.zig from registry.tsv.

The audit module (src/sab_audit.zig) imports this generated table.
Regeneration must be a no-op diff when the registry is fresh;
regen.sh --check enforces that (the anti-staleness gate).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))


def zig_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    reg_path = os.path.join(HERE, "registry.tsv")
    stamps = {}
    rows = []
    with open(reg_path, encoding="utf-8") as fh:
        lines = [ln.rstrip("\n") for ln in fh]
    for ln in lines:
        if ln.startswith("# plugin_head:"):
            stamps["plugin"] = ln.split(":", 1)[1].strip()
        elif ln.startswith("# sa_std_head:"):
            stamps["sa_std"] = ln.split(":", 1)[1].strip()
    header = None
    for ln in lines:
        if ln.startswith("#") or not ln.strip():
            continue
        parts = ln.split("\t")
        if header is None:
            header = parts
            continue
        parts += [""] * (len(header) - len(parts))
        rows.append(dict(zip(header, parts)))

    out = []
    out.append("//! sab_audit_registry.zig — GENERATED by tools/sab_audit/emit_registry_zig.py")
    out.append("//! from tools/sab_audit/registry.tsv (probe-matrix output).")
    out.append("//! Do not edit by hand: regenerate with tools/sab_audit/regen.sh.")
    out.append("//! Registry stamps: plugin_head=%s sa_std_head=%s"
               % (stamps.get("plugin", "?"), stamps.get("sa_std", "?")))
    out.append("")
    out.append("const std = @import(\"std\");")
    out.append("")
    out.append("pub const Status = enum { ok, fail, checkfail, decl };")
    out.append("")
    out.append("pub const Entry = struct {")
    out.append("    symbol: []const u8,")
    out.append("    class: []const u8,")
    out.append("    text: Status,")
    out.append("    sab: Status,")
    out.append("    signature: []const u8,")
    out.append("};")
    out.append("")
    out.append("pub const entries: []const Entry = &.{")
    for r in rows:
        out.append("    .{ .symbol = %s, .class = %s, .text = .%s, .sab = .%s, .signature = %s },"
                   % (zig_str(r["symbol"]), zig_str(r["class"]), r["text"], r["sab"],
                      zig_str(r["signature"])))
    out.append("};")
    out.append("")
    out.append("pub fn lookup(symbol: []const u8) ?Entry {")
    out.append("    for (entries) |entry| {")
    out.append("        if (std.mem.eql(u8, entry.symbol, symbol)) return entry;")
    out.append("    }")
    out.append("    return null;")
    out.append("}")
    out.append("")
    dest = os.path.join(REPO, "src", "sab_audit_registry.zig")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("emit_registry_zig: %d entries -> %s" % (len(rows), dest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
