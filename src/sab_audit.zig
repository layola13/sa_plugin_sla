//! sab_audit.zig — DEF-SAB-AUDIT (form A′): post-check dual-backend
//! registration audit.
//!
//! Why this exists: the checker's acceptance of a call and the SAB
//! backend's ability to lower it live in separate, hand-written
//! cascades (see the DEF-SAB-AUDIT mapping report). A call can
//! therefore pass checking and only fail inside SAB codegen —
//! first-failure-only, one program at a time (UnknownRegister /
//! Undefined call / UnsupportedSabDirectFeature). This module
//! closes that hole at check time: it walks the checked program,
//! classifies every resolved call, and for the "hardcoded class"
//! (calls whose acceptance lives in the checker/codegen cascades
//! rather than in the enumerable declaration plane) it consults the
//! registration registry — a data table generated by compile probing
//! (tools/sab_audit/, src/sab_audit_registry.zig) — and reports
//! EVERY missing backend registration in one pass, before codegen.
//!
//! Doctrine (user rulings 2026-11-03 23:40 / 23:41):
//! - SAB is the production path; SA text is the teaching /
//!   decompile-debug mirror. A registration missing on a targeted
//!   backend is a HARD finding. A registration missing only on a
//!   non-targeted backend is reported as a mirror-distortion
//!   finding (the mirror disagrees with production: still a defect,
//!   never silently dropped, but it does not block a build that does
//!   not target that backend).
//! - There is NO fallback exit: this audit never reroutes, degrades,
//!   or substitutes one backend for another. Missing means missing,
//!   listed in full.
//!
//! Three-state registry semantics per symbol/backend:
//! - ok:        a probe program exercising the symbol compiled and
//!              ran green on that backend.
//! - fail:      the probe failed on that backend (signature kept).
//!              Hard finding when the backend is targeted, mirror
//!              finding otherwise.
//! - checkfail: the probe was rejected by the (backend-independent)
//!              checker itself, so no checked program can reach the
//!              symbol through that probe shape. If a checked
//!              program nevertheless uses it (different shape), the
//!              entry is reported as unprobed — visible, non-hard.
//! A hardcoded-class symbol with NO registry entry at all is
//! reported as unprobed (listed in full, non-hard): the registry is
//! the growth surface — new cascade-accepted names land in the
//! audit's unprobed list instead of exploding inside codegen, and
//! the probe matrix (tools/sab_audit/regen.sh) is how they get
//! classified.
//!
//! Classification (mirrors the checker's own known-callee logic,
//! cf. TypeChecker.walkTaintCall):
//! - immediately-invoked closure callees: not name-dispatched, skip.
//! - associated calls (Type::name) and any name present in the
//!   checker's enumerable declaration plane (funcs / extern_funcs /
//!   imported_function_signatures / macros): declared plane —
//!   lowered through generic paths on both backends, not
//!   per-symbol registered, skip.
//! - imported SA macros (imported_macros): the macro_bridge class.
//!   Their lowering is a per-macro bridge in each backend, which is
//!   precisely where the SAB UnknownRegister family lives, so they
//!   are registry-checked by bare name (MAP_KEYS, MAP_DEL, ...).
//! - method calls whose receiver type has a declared impl method
//!   (TypeChecker.methodForType): declared plane, skip.
//! - everything else named: hardcoded class → registry lookup.
//!   Symbol key = "<ReceiverType>.<name>" for method calls
//!   (receiver type from the checker's expr_types), bare "<name>"
//!   for free calls. One shape refinement: an `iter` call whose
//!   result is NOT consumed directly as the receiver of an
//!   enclosing call is keyed "<ReceiverType>.iter[held]" — held
//!   iterators lower through a different (and at the measured head
//!   broken) shape than chained ones, and the registry records
//!   them separately.
//!
//! Coverage: every function body, every impl/overload method body,
//! and every @test body PRESENT in the checked AST. (The check and
//! build pipelines skip parsing @test bodies; the test pipeline
//! parses them, so a test-path wiring audits them in full.)
//! Macro declaration bodies are expansion templates and are not
//! walked: the calls they produce materialize at expansion sites in
//! checked code, where this walk sees them.
//!
//! Lenient mode (auditProgramLenient): for programs whose check
//! failed partway (e.g. the pre-E0 `using` surface, rejected by the
//! checker itself), receiver type names are recovered syntactically
//! — parameter and let annotations, struct-literal bindings, and
//! field types of declared structs — so the attempted hardcoded
//! symbols can still be listed in full. Findings produced in
//! lenient mode carry the "lenient:" signature prefix and are
//! evidence about intent, not about a checked program.
//!
//! This module is read-only by construction: it receives the
//! TypeChecker and the AST and hands back findings; it has no
//! writer into either, and no path into codegen.

const std = @import("std");
const ast = @import("ast.zig");
const type_checker = @import("type_checker.zig");
const registry = @import("sab_audit_registry.zig");

pub const Backend = enum { text, sab };

/// Explicit error set: the audit only allocates. (The walk is
/// mutually recursive; an inferred set would form a dependency
/// loop in this toolchain.)
pub const AuditError = error{OutOfMemory};

pub const Severity = enum {
    /// Missing on a targeted backend: blocks, listed in full.
    hard,
    /// Missing only on a non-targeted backend: mirror distortion.
    mirror,
    /// No usable registry verdict: listed, non-blocking.
    unprobed,
};

pub const Finding = struct {
    symbol: []const u8,
    class: []const u8,
    /// Null for unprobed findings (no per-backend verdict exists).
    backend: ?Backend,
    severity: Severity,
    signature: []const u8,
};

pub const Targets = struct {
    text: bool = false,
    sab: bool = true,

    /// Production default per the mapping ruling: check audits
    /// against {SAB}; text gaps surface as mirror findings.
    pub const production: Targets = .{ .text = false, .sab = true };
    /// Test-path target: both backends are produced, both are hard.
    pub const both: Targets = .{ .text = true, .sab = true };
    /// Emitting the text mirror only: text is hard, SAB is mirror.
    pub const mirror_only: Targets = .{ .text = true, .sab = false };
};

pub const SymbolUse = struct {
    symbol: []const u8,
    class: []const u8,
};

pub const AuditResult = struct {
    uses: []SymbolUse,
    findings: []Finding,

    pub fn hardCount(self: AuditResult) usize {
        var n: usize = 0;
        for (self.findings) |f| {
            if (f.severity == .hard) n += 1;
        }
        return n;
    }
};

/// Strict audit: receiver types come from the checker's expr_types.
/// Call only on a program that passed checkProgram.
pub fn auditProgram(
    allocator: std.mem.Allocator,
    tc: *type_checker.TypeChecker,
    program: *const ast.Node,
    targets: Targets,
) AuditError!AuditResult {
    var engine = Engine{ .allocator = allocator, .tc = tc, .lenient = false };
    return engine.run(program, targets);
}

/// Lenient audit: receiver type names fall back to a syntactic
/// environment when the checker has no type for a node (programs
/// whose check failed partway). Findings are prefixed "lenient:".
pub fn auditProgramLenient(
    allocator: std.mem.Allocator,
    tc: *type_checker.TypeChecker,
    program: *const ast.Node,
    targets: Targets,
) AuditError!AuditResult {
    var engine = Engine{ .allocator = allocator, .tc = tc, .lenient = true };
    return engine.run(program, targets);
}

/// Registry row shape is owned by the generated table; re-exported
/// so callers never import the generated file directly.
pub const RegistryEntry = registry.Entry;
pub const registry_entries: []const RegistryEntry = registry.entries;

const Engine = struct {
    allocator: std.mem.Allocator,
    tc: *type_checker.TypeChecker,
    lenient: bool,
    uses: std.StringHashMap(SymbolUse) = undefined,
    /// Lenient environment: declared struct field type names,
    /// struct name -> (field name -> field type name).
    struct_fields: std.StringHashMap(std.StringHashMap([]const u8)) = undefined,
    /// Lenient environment: lexical name -> type name bindings.
    bindings: std.array_list.Managed(Binding) = undefined,
    /// Lenient environment: the impl target type while inside an
    /// impl method (for `self` receivers).
    self_ty_name: ?[]const u8 = null,
    /// Walk context: true while the node being walked sits in the
    /// receiver position (args[0]) of an enclosing call. Only used
    /// to key `iter` calls: a chained iterator (v.iter().sum()) and
    /// a held iterator (let it = v.iter(); it.sum()) lower through
    /// different shapes with different registry verdicts — the
    /// held form is keyed "<Recv>.iter[held]".
    in_receiver_chain: bool = false,

    const Binding = struct { name: []const u8, ty_name: []const u8 };

    fn run(self: *Engine, program: *const ast.Node, targets: Targets) AuditError!AuditResult {
        self.uses = std.StringHashMap(SymbolUse).init(self.allocator);
        self.struct_fields = std.StringHashMap(std.StringHashMap([]const u8)).init(self.allocator);
        self.bindings = std.array_list.Managed(Binding).init(self.allocator);
        if (self.lenient) try self.collectStructFields(program);
        try self.walkProgram(program);

        var uses = std.array_list.Managed(SymbolUse).init(self.allocator);
        var uit = self.uses.valueIterator();
        while (uit.next()) |u| try uses.append(u.*);
        std.mem.sort(SymbolUse, uses.items, {}, symbolUseLessThan);

        var findings = std.array_list.Managed(Finding).init(self.allocator);
        for (uses.items) |use| try self.findingsFor(use, targets, &findings);
        std.mem.sort(Finding, findings.items, {}, findingLessThan);

        return .{
            .uses = try uses.toOwnedSlice(),
            .findings = try findings.toOwnedSlice(),
        };
    }

    fn findingsFor(
        self: *Engine,
        use: SymbolUse,
        targets: Targets,
        out: *std.array_list.Managed(Finding),
    ) AuditError!void {
        const entry = registry.lookup(use.symbol);
        if (entry == null) {
            try out.append(.{
                .symbol = use.symbol,
                .class = use.class,
                .backend = null,
                .severity = .unprobed,
                .signature = if (self.lenient) "lenient:no registry entry" else "no registry entry",
            });
            return;
        }
        const e = entry.?;
        inline for (.{ Backend.text, Backend.sab }) |backend| {
            const status = if (backend == .text) e.text else e.sab;
            switch (status) {
                .ok => {},
                .fail => {
                    const targeted = if (backend == .text) targets.text else targets.sab;
                    try out.append(.{
                        .symbol = use.symbol,
                        .class = use.class,
                        .backend = backend,
                        .severity = if (targeted) Severity.hard else Severity.mirror,
                        .signature = if (self.lenient)
                            try std.fmt.allocPrint(self.allocator, "lenient:{s}", .{e.signature})
                        else
                            e.signature,
                    });
                },
                .checkfail, .decl => {
                    // A probe shape the checker rejected proves
                    // nothing about this checked use; surface it as
                    // unprobed rather than guessing either way.
                    try out.append(.{
                        .symbol = use.symbol,
                        .class = use.class,
                        .backend = backend,
                        .severity = .unprobed,
                        .signature = if (status == .checkfail)
                            "registry verdict is checker-rejected in probe shape"
                        else
                            "registry verdict is declaration-plane",
                    });
                },
            }
        }
    }

    // ---------------------------------------------------------------
    // Declaration-plane membership (the checker's own test).
    // ---------------------------------------------------------------

    fn isDeclaredName(self: *Engine, name: []const u8) bool {
        const tc = self.tc;
        return tc.funcs.contains(name) or
            tc.extern_funcs.contains(name) or
            tc.imported_function_signatures.contains(name) or
            tc.macros.contains(name);
    }

    /// Imported SA macros are NOT the declared plane for audit
    /// purposes: their lowering runs through the per-macro bridge
    /// (lowering_rules.planImportedMacroCall -> each backend's
    /// genImportedMacroCall), which is exactly where the SAB
    /// UnknownRegister family lives (MAP_KEYS &co). They form the
    /// macro_bridge class and are registry-checked by name.
    fn isImportedMacroName(self: *Engine, name: []const u8) bool {
        return self.tc.imported_macros.contains(name);
    }

    // ---------------------------------------------------------------
    // Call classification.
    // ---------------------------------------------------------------

    /// Free-form cascade builtins: names the checker resolves as
    /// free functions even though the parser gives their calls the
    /// same shape as method calls (arguments, no receiver). `panic`
    /// is the proven case — it appears in every @test body and is
    /// also synthesized by syntax_lowering. Keep this list minimal
    /// and evidence-driven: a name belongs here only when the
    /// checker demonstrably treats it as a free function.
    const free_builtins = [_][]const u8{"panic"};

    fn isFreeBuiltin(name: []const u8) bool {
        for (free_builtins) |builtin| {
            if (std.mem.eql(u8, name, builtin)) return true;
        }
        return false;
    }

    fn noteCall(self: *Engine, call: ast.CallExpr) AuditError!void {
        if (call.callee != null) return; // closure invocation: no name dispatch
        if (call.associated_target != null) return; // associated: declared plane
        if (self.isDeclaredName(call.func_name)) return; // declared plane
        if (self.isImportedMacroName(call.func_name)) {
            const gop = try self.uses.getOrPut(call.func_name);
            if (!gop.found_existing) {
                gop.value_ptr.* = .{ .symbol = call.func_name, .class = "macro_bridge" };
            }
            return;
        }
        if (isFreeBuiltin(call.func_name)) {
            const gop = try self.uses.getOrPut(call.func_name);
            if (!gop.found_existing) {
                gop.value_ptr.* = .{ .symbol = call.func_name, .class = "builtin" };
            }
            return;
        }

        if (call.args.len > 0) {
            // Method-call shape: args[0] is the receiver.
            const recv = self.receiverInfo(call.args[0]);
            if (recv.ty) |ty| {
                if (self.tc.methodForType(ty, call.func_name) != null) return; // impl method
            } else if (!std.mem.eql(u8, recv.name, "?")) {
                // Name-key form of the same declared-impl test
                // (methodForType keys funcs by "<Type>_<method>").
                const key = try std.fmt.allocPrint(self.allocator, "{s}_{s}", .{ recv.name, call.func_name });
                if (self.tc.funcs.contains(key)) return;
            }
            const held = std.mem.eql(u8, call.func_name, "iter") and !self.in_receiver_chain;
            const symbol = if (held)
                try std.fmt.allocPrint(self.allocator, "{s}.{s}[held]", .{ recv.name, call.func_name })
            else
                try std.fmt.allocPrint(self.allocator, "{s}.{s}", .{ recv.name, call.func_name });
            const gop = try self.uses.getOrPut(symbol);
            if (!gop.found_existing) {
                gop.value_ptr.* = .{ .symbol = symbol, .class = "method" };
            }
            return;
        }

        // Free call known to no table: a checker-cascade builtin.
        const gop = try self.uses.getOrPut(call.func_name);
        if (!gop.found_existing) {
            gop.value_ptr.* = .{ .symbol = call.func_name, .class = "builtin" };
        }
    }

    const ReceiverInfo = struct {
        name: []const u8,
        ty: ?*ast.Type,
    };

    fn receiverInfo(self: *Engine, node: *const ast.Node) ReceiverInfo {
        if (self.tc.expr_types.get(node)) |ty| {
            return .{ .name = self.typeName(ty) catch "?", .ty = ty };
        }
        if (self.lenient) {
            if (self.syntacticTypeName(node)) |name| {
                return .{ .name = name, .ty = null };
            }
        }
        return .{ .name = "?", .ty = null };
    }

    /// Canonical receiver-type name used in registry symbol keys.
    fn typeName(self: *Engine, ty: *const ast.Type) ![]const u8 {
        _ = self;
        return typeNameOf(ty);
    }

    /// Lenient syntactic receiver name: identifiers via bindings,
    /// field accesses via declared struct fields, struct literals
    /// and casts via their written type.
    fn syntacticTypeName(self: *Engine, node: *const ast.Node) ?[]const u8 {
        switch (node.*) {
            .identifier => |name| {
                if (std.mem.eql(u8, name, "self")) {
                    if (self.self_ty_name) |sn| return sn;
                }
                return self.lookupBinding(name);
            },
            .field_expr => |fe| {
                const base = self.syntacticTypeName(fe.expr) orelse return null;
                const fields = self.struct_fields.get(base) orelse return null;
                return fields.get(fe.field_name);
            },
            .struct_literal => |lit| return typeNameOf(lit.ty) catch null,
            .cast_expr => |cast| return typeNameOf(cast.ty) catch null,
            .call_expr => |call| {
                // `let m = HashMap::new();` — the binding's type is
                // the associated target.
                if (call.associated_target) |target| return target;
                return null;
            },
            .borrow_expr => |b| return self.syntacticTypeName(b.expr),
            .move_expr => |m| return self.syntacticTypeName(m.expr),
            .deref_expr => |d| return self.syntacticTypeName(d.expr),
            else => return null,
        }
    }

    fn lookupBinding(self: *Engine, name: []const u8) ?[]const u8 {
        var i = self.bindings.items.len;
        while (i > 0) {
            i -= 1;
            if (std.mem.eql(u8, self.bindings.items[i].name, name)) {
                return self.bindings.items[i].ty_name;
            }
        }
        return null;
    }

    fn bindName(self: *Engine, name: []const u8, ty_name: []const u8) void {
        self.bindings.append(.{ .name = name, .ty_name = ty_name }) catch {};
    }

    fn bindFromDecl(self: *Engine, name: []const u8, ty: ?*ast.Type, value: ?*const ast.Node) void {
        if (!self.lenient) return;
        if (ty) |t| {
            self.bindName(name, typeNameOf(t) catch return);
            return;
        }
        if (value) |v| {
            if (self.syntacticTypeName(v)) |tn| self.bindName(name, tn);
        }
    }

    fn pushParams(self: *Engine, params: []const ast.Param) void {
        if (!self.lenient) return;
        for (params) |param| {
            self.bindName(param.name, typeNameOf(param.ty) catch continue);
        }
    }

    // ---------------------------------------------------------------
    // Lenient environment: struct field table.
    // ---------------------------------------------------------------

    fn collectStructFields(self: *Engine, program: *const ast.Node) AuditError!void {
        if (program.* != .program) return;
        for (program.program.decls) |decl| {
            if (decl.* != .struct_decl) continue;
            const sd = decl.struct_decl;
            var fields = std.StringHashMap([]const u8).init(self.allocator);
            for (sd.fields) |field| {
                fields.put(field.name, typeNameOf(field.ty) catch continue) catch {};
            }
            try self.struct_fields.put(sd.name, fields);
        }
    }

    // ---------------------------------------------------------------
    // Walk. Covers every body-bearing declaration kind and the full
    // statement/expression grammar (modeled on check_hooks' walker,
    // extended to program level and @test bodies). Bindings use
    // mark/restore on one shared stack; no environment copies.
    // ---------------------------------------------------------------

    fn walkProgram(self: *Engine, program: *const ast.Node) AuditError!void {
        if (program.* != .program) {
            try self.walkNode(program);
            return;
        }
        for (program.program.decls) |decl| try self.walkDecl(decl);
    }

    fn walkDecl(self: *Engine, node: *const ast.Node) AuditError!void {
        switch (node.*) {
            .func_decl => |fd| {
                const mark = self.bindings.items.len;
                defer self.bindings.shrinkRetainingCapacity(mark);
                self.pushParams(fd.params);
                try self.walkStmts(fd.body);
            },
            .test_decl => |td| try self.walkStmts(td.body),
            .impl_decl => |id| {
                const saved_self = self.self_ty_name;
                defer self.self_ty_name = saved_self;
                if (id.target_ty.* == .user_defined) {
                    self.self_ty_name = id.target_ty.user_defined.name;
                }
                for (id.methods) |method| try self.walkDecl(method);
            },
            .overload_decl => |od| {
                for (od.methods) |method| try self.walkDecl(method);
            },
            // Macro bodies are expansion templates: not walked (see
            // module header). All other declarations carry no bodies.
            else => {},
        }
    }

    fn walkStmts(self: *Engine, stmts: []const *ast.Node) AuditError!void {
        const mark = self.bindings.items.len;
        defer self.bindings.shrinkRetainingCapacity(mark);
        for (stmts) |stmt| try self.walkNode(stmt);
    }

    fn walkNode(self: *Engine, node: *const ast.Node) AuditError!void {
        switch (node.*) {
            // Declarations nested in bodies (rare, but legal shapes).
            .func_decl, .test_decl, .impl_decl, .overload_decl => try self.walkDecl(node),
            // Statements
            .let_stmt => |s| {
                try self.walkNode(s.value);
                self.bindFromDecl(s.name, s.ty, s.value);
            },
            .const_stmt => |s| {
                try self.walkNode(s.value);
                self.bindFromDecl(s.name, s.ty, s.value);
            },
            .var_stmt => |s| self.bindFromDecl(s.name, s.ty, null),
            .let_destructure_stmt => |s| try self.walkNode(s.value),
            .let_else_stmt => |s| {
                try self.walkNode(s.value);
                try self.walkStmts(s.else_block);
            },
            .assign_stmt => |s| {
                try self.walkNode(s.target);
                try self.walkNode(s.value);
            },
            .block_stmt => |s| try self.walkStmts(s.body),
            .arena_stmt => |s| try self.walkStmts(s.body),
            .expr_stmt => |inner| try self.walkNode(inner),
            .return_stmt => |s| {
                if (s.value) |v| try self.walkNode(v);
            },
            .for_stmt => |s| {
                try self.walkNode(s.start);
                if (s.end) |e| try self.walkNode(e);
                const mark = self.bindings.items.len;
                defer self.bindings.shrinkRetainingCapacity(mark);
                self.bindName(s.var_name, "?");
                try self.walkStmts(s.body);
            },
            .while_stmt => |s| {
                try self.walkNode(s.cond);
                try self.walkStmts(s.body);
            },
            .break_stmt, .continue_stmt => {},
            .release_stmt => {},
            .defer_stmt => |s| try self.walkNode(s.call),
            .select_stmt => |s| {
                if (s.timeout_expr) |t| try self.walkNode(t);
                for (s.cases) |case| {
                    try self.walkNode(case.call);
                    try self.walkStmts(case.body);
                }
                if (s.default_body) |b| try self.walkStmts(b);
                if (s.timeout_body) |b| try self.walkStmts(b);
            },
            // Expressions
            .literal, .identifier, .generic_func_ref => {},
            .go_expr => |e| try self.walkNode(e.call),
            .if_expr => |e| {
                try self.walkNode(e.cond);
                if (e.let_chain) |chain| {
                    for (chain) |cond| try self.walkNode(cond.value);
                }
                try self.walkStmts(e.then_block);
                if (e.else_block) |b| try self.walkStmts(b);
            },
            .switch_expr => |e| {
                try self.walkNode(e.val);
                for (e.cases) |case| try self.walkStmts(case.body);
            },
            .match_expr => |e| {
                try self.walkNode(e.val);
                for (e.cases) |case| {
                    if (case.guard) |g| try self.walkNode(g);
                    try self.walkStmts(case.body);
                }
            },
            .unsafe_expr => |e| try self.walkStmts(e.body),
            .await_expr => |e| try self.walkNode(e.expr),
            .inline_asm_expr => {},
            .binary_expr => |e| {
                try self.walkNode(e.left);
                try self.walkNode(e.right);
            },
            .call_expr => |call| {
                try self.noteCall(call);
                if (call.callee) |callee| try self.walkNode(callee);
                for (call.args, 0..) |arg, i| {
                    const saved = self.in_receiver_chain;
                    self.in_receiver_chain = (i == 0);
                    try self.walkNode(arg);
                    self.in_receiver_chain = saved;
                }
            },
            .closure_literal => |e| {
                const mark = self.bindings.items.len;
                defer self.bindings.shrinkRetainingCapacity(mark);
                self.pushParams(e.params);
                try self.walkNode(e.body);
            },
            .borrow_expr => |e| try self.walkNode(e.expr),
            .move_expr => |e| try self.walkNode(e.expr),
            .deref_expr => |e| try self.walkNode(e.expr),
            .cast_expr => |e| try self.walkNode(e.expr),
            .field_expr => |e| try self.walkNode(e.expr),
            .struct_literal => |e| {
                for (e.fields) |f| try self.walkNode(f.value);
                if (e.update_expr) |u| try self.walkNode(u);
            },
            .enum_literal => |e| {
                for (e.fields) |f| try self.walkNode(f.value);
            },
            .tuple_literal => |e| {
                for (e.elements) |el| try self.walkNode(el);
            },
            .array_literal => |e| {
                for (e.elements) |el| try self.walkNode(el);
            },
            .repeat_array_literal => |e| try self.walkNode(e.value),
            .index_expr => |e| {
                try self.walkNode(e.target);
                try self.walkNode(e.index);
            },
            .slice_expr => |e| {
                try self.walkNode(e.target);
                try self.walkNode(e.start);
                try self.walkNode(e.end);
            },
            .try_expr => |e| try self.walkNode(e.expr),
            // Program root is handled by walkProgram; any remaining
            // kind is a declaration without a body.
            else => {},
        }
    }
};

fn typeNameOf(ty: *const ast.Type) ![]const u8 {
    return switch (ty.*) {
        .infer => "?",
        .primitive => |p| @tagName(p),
        .pointer => |inner| typeNameOf(inner),
        .borrow => |inner| typeNameOf(inner),
        .future => |inner| typeNameOf(inner),
        .array => "Array",
        .tuple => "Tuple",
        .closure, .fn_ptr => "Fn",
        .user_defined => |ud| ud.name,
    };
}

fn symbolUseLessThan(_: void, a: SymbolUse, b: SymbolUse) bool {
    return std.mem.order(u8, a.symbol, b.symbol) == .lt;
}

fn findingLessThan(_: void, a: Finding, b: Finding) bool {
    const by_symbol = std.mem.order(u8, a.symbol, b.symbol);
    if (by_symbol != .eq) return by_symbol == .lt;
    const ab: u8 = if (a.backend) |be| @intFromEnum(be) else 255;
    const bb: u8 = if (b.backend) |be| @intFromEnum(be) else 255;
    return ab < bb;
}
