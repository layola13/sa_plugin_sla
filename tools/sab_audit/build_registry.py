#!/usr/bin/env python3
"""DEF-SAB-AUDIT registry builder.

Joins the probe matrix results (results.tsv, produced by
run_matrix.sh) with the generator manifest and the declared-plane
rows, and writes registry.tsv — the checked-in registration
registry consumed by emit_registry_zig.py (-> src/sab_audit_registry.zig
-> src/sab_audit.zig).

Per-symbol status derivation, per backend:
  probe verdict ok                      -> ok
  probe verdict fail, phase=check       -> checkfail (both backends:
                                           the checker is shared)
  probe verdict fail, phase=codegen/run -> fail (signature kept)
A symbol whose probe file serves several symbols (using_ext) takes
the file's verdict for each of them.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def read_tsv(path):
    with open(path, encoding="utf-8") as fh:
        lines = [ln.rstrip("\n") for ln in fh if ln.strip()]
    if not lines:
        return [], []
    header = lines[0].split("\t")
    rows = []
    for ln in lines[1:]:
        parts = ln.split("\t")
        parts += [""] * (len(header) - len(parts))
        rows.append(dict(zip(header, parts)))
    return header, rows


def git_head(path):
    try:
        out = subprocess.run(["git", "-C", path, "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=30)
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def main():
    results_path = os.path.join(HERE, "results.tsv")
    if not os.path.exists(results_path):
        print("build_registry: results.tsv missing — run run_matrix.sh first", file=sys.stderr)
        return 1
    _, results = read_tsv(results_path)
    _, manifest = read_tsv(os.path.join(HERE, "manifest.tsv"))
    _, decl_rows = read_tsv(os.path.join(HERE, "decl_rows.tsv"))

    # probe_id -> backend -> (verdict, phase, signature)
    by_probe = {}
    for r in results:
        by_probe.setdefault(r["probe_id"], {})[r["backend"]] = r

    plugin_head = os.environ.get("AUDIT_PLUGIN_HEAD") or git_head(os.path.join(HERE, "..", ".."))
    sa_std_head = os.environ.get("AUDIT_SA_STD_HEAD", "unknown")

    # No wall-clock stamp: the registry must be byte-reproducible for
    # a given (plugin tree, sa_std tree) pair so that the regen diff
    # gate can prove freshness. The head pair IS the stamp.
    lines = []
    lines.append("# DEF-SAB-AUDIT registration registry — GENERATED by tools/sab_audit/regen.sh; do not edit by hand.")
    lines.append("# plugin_head: %s" % plugin_head)
    lines.append("# sa_std_head: %s" % sa_std_head)
    lines.append("symbol\tclass\ttext\tsab\tsignature\tprobe_id\tnote")

    body = []
    for row in manifest:
        pid = row["probe_id"]
        per = by_probe.get(pid, {})
        statuses = {}
        signatures = []
        for backend in ("text", "sab"):
            r = per.get(backend)
            if r is None:
                statuses[backend] = "checkfail"
                signatures.append("%s:no-result" % backend)
                continue
            if r["verdict"] == "ok":
                statuses[backend] = "ok"
            elif r["phase"] == "check":
                statuses[backend] = "checkfail"
                signatures.append("%s:check:%s" % (backend, r["signature"]))
            else:
                statuses[backend] = "fail"
                signatures.append("%s:%s:%s" % (backend, r["phase"], r["signature"]))
        body.append("\t".join([
            row["symbol"], row["class"], statuses["text"], statuses["sab"],
            "; ".join(signatures), pid, row["note"],
        ]))
    for row in decl_rows:
        body.append("\t".join([
            row["symbol"], row["class"], row["text"], row["sab"],
            row["signature"], row["probe_id"], row["note"],
        ]))
    body.sort()
    lines.extend(body)
    with open(os.path.join(HERE, "registry.tsv"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("build_registry: %d rows" % len(body))
    return 0


if __name__ == "__main__":
    sys.exit(main())
